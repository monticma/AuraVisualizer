/**
 * agent-context.ts — Pure generators for Aura's agent-facing context files (V3-10).
 *
 * An AI agent that lands in an unfamiliar repository has no idea which files are
 * dangerous. Aura already computes exactly that (risk score, reasons, cycles,
 * dead exports); this module turns it into files an agent actually reads:
 *
 *   • `.aura/hotspots.json`  — the same payload the `aura_get_hotspots` tool returns
 *   • `.aura/HOTSPOTS.md`    — the same data, human-readable (local cache)
 *   • a delimited block inside `AGENTS.md` / `.github/copilot-instructions.md` /
 *     `CLAUDE.md` — the only part meant to be committed and shared
 *
 * The block is injected between `<!-- aura:begin … -->` and `<!-- aura:end -->`,
 * so regenerating never duplicates it and never touches the prose around it.
 * Only paths and metrics go in — never source code.
 *
 * No `vscode` import — the module is unit-testable in plain Node.
 */

/** Marker prefix; the suffix carries the "generated by" hint. */
export const AGENT_BLOCK_BEGIN = '<!-- aura:begin';
/** Closing marker, matched exactly (or with surrounding whitespace). */
export const AGENT_BLOCK_END = '<!-- aura:end -->';

/** Rows listed inside the injected block (kept short on purpose: it is prompt context). */
export const AGENT_CONTEXT_LIMIT = 10;
/** Rows listed in the standalone `.aura/HOTSPOTS.md`. */
export const AGENT_MARKDOWN_LIMIT = 25;

/** Candidate instruction files, in priority order. */
export const AGENT_CONTEXT_TARGETS = [
    'AGENTS.md',
    '.github/copilot-instructions.md',
    'CLAUDE.md',
] as const;

/** Created when none of `AGENT_CONTEXT_TARGETS` exists yet. */
export const AGENT_CONTEXT_DEFAULT_TARGET = 'AGENTS.md';

/** File names written under `.aura/` (git-ignored, local only). */
export const AGENT_CONTEXT_JSON = 'hotspots.json';
export const AGENT_CONTEXT_MARKDOWN = 'HOTSPOTS.md';

/** Why each reason is a plain sentence ("complexity 489 (top 1% of the repo)"). */
export const AGENT_REASONS_PER_ROW = 3;

/** The slice of a risk hotspot the generators need (`RiskHotspot` is assignable). */
export interface AgentHotspot {
    file: string;
    risk_score: number;
    bucket?: string;
    top?: string | null;
    reasons?: readonly string[];
}

export interface AgentContextInput {
    /** Hotspots to render; re-sorted here so the output is deterministic. */
    hotspots: readonly AgentHotspot[];
    /** Risk window in days (`auraVisualizer.riskWindow`). */
    windowDays: number;
    /** How many files were scored in total (not just the listed ones). */
    total: number;
    /** ISO timestamp of the generation — passed in so the module stays pure. */
    generatedAt: string;
    /** Repository counters; each is omitted from the output when `undefined`. */
    cycles?: number;
    deadCode?: number;
    archViolations?: number;
    /** Rows in the injected block (default `AGENT_CONTEXT_LIMIT`). */
    limit?: number;
}

export interface AgentContextTarget {
    /** Workspace-relative path, slash separated. */
    path: string;
    /** True when the file has to be created (no instruction file existed). */
    create: boolean;
}

// ============================================================
// Target selection
// ============================================================

function normalizeRelative(file: string): string {
    return file.replace(/\\/g, '/').replace(/^\.\//, '').trim();
}

/**
 * Pick the instruction file to inject into: the first of
 * `AGENT_CONTEXT_TARGETS` that already exists (case-insensitive match, the
 * existing spelling is preserved), otherwise `AGENTS.md` marked `create`.
 */
export function pickAgentContextTarget(existing: readonly string[]): AgentContextTarget {
    const present = new Map<string, string>();
    for (const file of existing) {
        const normalized = normalizeRelative(file);
        if (normalized) present.set(normalized.toLowerCase(), normalized);
    }
    for (const candidate of AGENT_CONTEXT_TARGETS) {
        const found = present.get(candidate.toLowerCase());
        if (found) return { path: found, create: false };
    }
    return { path: AGENT_CONTEXT_DEFAULT_TARGET, create: true };
}

/** True when `text` already carries an Aura block (used to decide create-vs-update). */
export function hasAgentBlock(text: string): boolean {
    return text.includes(AGENT_BLOCK_BEGIN);
}

// ============================================================
// Rendering
// ============================================================

function formatScore(score: number): string {
    const rounded = Math.round((Number.isFinite(score) ? score : 0) * 10) / 10;
    return rounded.toFixed(1).replace(/\.0$/, '');
}

/** One-line, table-safe rendering of a reason list. */
export function reasonSummary(reasons: readonly string[] | undefined, limit = AGENT_REASONS_PER_ROW): string {
    if (!reasons || reasons.length === 0) return '—';
    const parts: string[] = [];
    for (const reason of reasons.slice(0, limit)) {
        const clean = reason.replace(/\s+/g, ' ').replace(/\|/g, '/').trim();
        if (clean) parts.push(clean);
    }
    return parts.length ? parts.join(' · ') : '—';
}

/** Descending score, then path — stable output whatever the input order. */
export function sortHotspots(hotspots: readonly AgentHotspot[]): AgentHotspot[] {
    return [...hotspots].sort((a, b) =>
        b.risk_score - a.risk_score || a.file.localeCompare(b.file));
}

function headline(input: AgentContextInput): string {
    const scored = Math.max(input.total, input.hotspots.length);
    const listed = Math.min(input.hotspots.length, input.limit ?? AGENT_CONTEXT_LIMIT);
    if (scored === 0) return 'No file is scored yet.';
    if (scored === listed) {
        return `${scored} file${scored === 1 ? '' : 's'} scored over the last ${input.windowDays} days — all of them listed below.`;
    }
    return `${scored} files scored over the last ${input.windowDays} days; these ${listed} carry most of the risk.`;
}

function healthLine(input: AgentContextInput): string | undefined {
    const parts: string[] = [];
    if (typeof input.cycles === 'number' && input.cycles > 0) {
        parts.push(`${input.cycles} dependency cycle${input.cycles === 1 ? '' : 's'}`);
    }
    if (typeof input.deadCode === 'number' && input.deadCode > 0) {
        parts.push(`${input.deadCode} dead export${input.deadCode === 1 ? '' : 's'}`);
    }
    if (typeof input.archViolations === 'number' && input.archViolations > 0) {
        parts.push(`${input.archViolations} new architecture violation${input.archViolations === 1 ? '' : 's'}`);
    }
    return parts.length ? `Repo health: ${parts.join(' · ')}.` : undefined;
}

function hotspotRows(hotspots: readonly AgentHotspot[], limit: number): string[] {
    const rows = ['| File | Risk | Why |', '| --- | --- | --- |'];
    for (const hotspot of hotspots.slice(0, limit)) {
        rows.push(`| \`${normalizeRelative(hotspot.file)}\` | ${formatScore(hotspot.risk_score)} | ${reasonSummary(hotspot.reasons)} |`);
    }
    return rows;
}

/** ISO timestamp → `YYYY-MM-DD` (falls back to the raw string when unparseable). */
export function isoDate(value: string): string {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return value;
    return date.toISOString().slice(0, 10);
}

/**
 * The delimited block injected into an agent instruction file. Deliberately
 * short: it is prompt context, not a report — the full data lives in
 * `.aura/HOTSPOTS.md`.
 */
export function renderAgentBlock(input: AgentContextInput): string {
    const limit = Math.max(1, input.limit ?? AGENT_CONTEXT_LIMIT);
    const sorted = sortHotspots(input.hotspots);
    const lines: string[] = [
        `${AGENT_BLOCK_BEGIN} — generated by Aura Visualizer on ${isoDate(input.generatedAt)}, do not edit by hand -->`,
        `## Aura risk hotspots · ${input.windowDays}-day window · ${isoDate(input.generatedAt)}`,
        '',
        headline(input),
        '',
        ...hotspotRows(sorted, limit),
    ];
    const health = healthLine(input);
    if (health) lines.push('', health);
    lines.push(
        '',
        '> Before opening files, query the Aura MCP tools (`aura_get_hotspots`,',
        '> `aura_find_dependents`, `aura_impact`) — they return the same data with paths.',
        AGENT_BLOCK_END,
    );
    return lines.join('\n');
}

/** Full `.aura/HOTSPOTS.md` — more rows and full reasons, still code-free. */
export function renderHotspotsMarkdown(
    input: AgentContextInput,
    limit = AGENT_MARKDOWN_LIMIT,
): string {
    const sorted = sortHotspots(input.hotspots);
    const rows: string[] = ['| # | File | Risk | Bucket | Why |', '| --- | --- | --- | --- | --- |'];
    sorted.slice(0, Math.max(1, limit)).forEach((hotspot, index) => {
        const bucket = (hotspot.bucket || '—').replace(/\|/g, '/');
        const reasons = hotspot.reasons && hotspot.reasons.length
            ? hotspot.reasons.map(r => r.replace(/\s+/g, ' ').replace(/\|/g, '/').trim()).filter(Boolean).join(' · ')
            : '—';
        rows.push(`| ${index + 1} | \`${normalizeRelative(hotspot.file)}\` | ${formatScore(hotspot.risk_score)} | ${bucket} | ${reasons} |`);
    });

    const lines: string[] = [
        '# Aura — risk hotspots',
        '',
        `Generated ${isoDate(input.generatedAt)} · ${input.windowDays}-day window · ${Math.max(input.total, input.hotspots.length)} files scored.`,
        '',
        '> Local cache (`.aura/` is git-ignored). The shareable summary is the',
        '> `aura:begin` / `aura:end` block of your agent instruction file.',
        '',
        ...rows,
    ];
    const health = healthLine(input);
    if (health) lines.push('', `## Repo health`, '', `- ${health.replace(/^Repo health: /, '').replace(/\.$/, '')}`);
    lines.push('', `Machine-readable copy: \`.aura/${AGENT_CONTEXT_JSON}\`.`, '');
    return lines.join('\n');
}

/** Pretty JSON with a trailing newline — byte-stable across runs. */
export function renderHotspotsJson(payload: unknown): string {
    return `${JSON.stringify(payload, null, 2)}\n`;
}

/** Notification wording, kept here so it is covered by tests. */
export function agentContextMessage(target: string, input: AgentContextInput): string {
    const listed = Math.min(input.hotspots.length, input.limit ?? AGENT_CONTEXT_LIMIT);
    return `Aura: agent context updated in ${target} (${listed} hotspot${listed === 1 ? '' : 's'}, ${input.windowDays}-day window)`;
}

// ============================================================
// Injection
// ============================================================

function dominantEol(text: string): string {
    return text.includes('\r\n') ? '\r\n' : '\n';
}

function toLines(text: string): string[] {
    return text.replace(/\r\n/g, '\n').split('\n');
}

/**
 * Replace (or append) the Aura block in `existing`.
 *
 * Guarantees: idempotent (running twice yields the same text), the prose
 * outside the markers is untouched, the EOL style is preserved, and a
 * half-broken block (begin without end) is repaired instead of duplicated.
 */
export function injectAgentBlock(existing: string | undefined, block: string): string {
    const source = existing ?? '';
    const eol = dominantEol(source);
    const blockLines = toLines(block).filter((line, index, all) =>
        !(index === all.length - 1 && line === ''));
    const lines = source.length ? toLines(source) : [];

    const beginIndex = lines.findIndex(line => line.trim().startsWith(AGENT_BLOCK_BEGIN));
    let result: string[];
    if (beginIndex >= 0) {
        const endIndex = lines.findIndex((line, index) =>
            index >= beginIndex && line.includes(AGENT_BLOCK_END));
        const head = lines.slice(0, beginIndex);
        // A block without a closing marker is ours and broken: drop it to EOF.
        const tail = endIndex >= 0 ? lines.slice(endIndex + 1) : [];
        result = [...head, ...blockLines, ...tail];
    } else {
        const head = lines.slice();
        while (head.length > 0 && head[head.length - 1].trim() === '') head.pop();
        result = head.length > 0 ? [...head, '', ...blockLines] : [...blockLines];
    }

    const joined = result.join(eol);
    return joined.endsWith(eol) ? joined : `${joined}${eol}`;
}
